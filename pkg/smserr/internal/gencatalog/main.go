// Command gencatalog renders pkg/smserr.Catalog as docs/error-catalog.md.
// It is invoked by `go generate ./pkg/smserr/...` (see the //go:generate
// directive in pkg/smserr/catalog.go) and must never be run by hand against
// a different catalog source — the Go catalog in pkg/smserr is the single
// source of truth (ARCHITECTURE.md §12.3: "An error-catalog.md is generated
// from code for client teams.").
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"sort"

	"github.com/amirandarabi/sms-manager/pkg/smserr"
)

const header = `<!-- Code generated by ` + "`go generate ./pkg/smserr/...`" + `. DO NOT EDIT. -->
<!-- Source: pkg/smserr/catalog.go (ARCHITECTURE.md §12.2). -->

# SMS Manager error catalog

Every error returned by any SMS Manager service, adapter, or handler uses one
of the ` + "`SMS-xxxx`" + ` codes below (ARCHITECTURE.md §12). Clients must branch on
` + "`code`" + `/` + "`class`" + `, never on message text.

This catalog is intentionally partial: it currently covers the ` + "`SMS-1xxx`" + `
(auth) and ` + "`SMS-9xxx`" + ` (internal) ranges only, enough to prove the
generation pipeline. ` + "`SMS-2xxx`" + `..` + "`SMS-5xxx`" + ` are filled in as Phase 1
provider and API stories land.

| Code | Class | HTTP status | Retryable | Title | Description |
|---|---|---|---|---|---|
`

func main() {
	outPath, err := catalogDocPath()
	if err != nil {
		log.Fatalf("gencatalog: %v", err)
	}

	entries := append([]smserr.CatalogEntry(nil), smserr.Catalog...)
	sort.Slice(entries, func(i, j int) bool { return entries[i].Code < entries[j].Code })

	var buf bytes.Buffer
	buf.WriteString(header)
	for _, e := range entries {
		fmt.Fprintf(&buf, "| `%s` | `%s` | %d | %t | %s | %s |\n",
			e.Code, e.Class, e.HTTPStatus, e.Retryable, e.Title, e.Description)
	}

	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		log.Fatalf("gencatalog: creating docs dir: %v", err)
	}
	if err := os.WriteFile(outPath, buf.Bytes(), 0o644); err != nil {
		log.Fatalf("gencatalog: writing %s: %v", outPath, err)
	}
	fmt.Printf("gencatalog: wrote %s (%d codes)\n", outPath, len(entries))
}

// catalogDocPath returns the absolute path to docs/error-catalog.md,
// computed from this source file's own location (via runtime.Caller)
// rather than the process's working directory, so `go generate` produces
// the same result whether invoked from the repo root or from pkg/smserr.
func catalogDocPath() (string, error) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("could not determine source location")
	}
	// thisFile: <repo>/pkg/smserr/internal/gencatalog/main.go
	repoRoot := filepath.Join(filepath.Dir(thisFile), "..", "..", "..", "..")
	return filepath.Join(repoRoot, "docs", "error-catalog.md"), nil
}
